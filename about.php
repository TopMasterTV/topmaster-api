<h1>TOP MASTER</h1>

<p>TOP MASTER é um aplicativo desenvolvido para Roku que organiza e reproduz conteúdos previamente vinculados à conta do usuário.</p>

<h2>Como funciona</h2>
<p>O usuário acessa o aplicativo utilizando uma conta válida. Após a autenticação, o TOP MASTER apresenta os conteúdos já associados ao login utilizado.</p>

<h2>O que o TOP MASTER não faz</h2>
<p>O TOP MASTER não vende, fornece, comercializa, hospeda ou adiciona canais, filmes, séries ou outros conteúdos. O aplicativo funciona exclusivamente como leitor e reprodutor de mídia.</p>

<h2>Recursos</h2>
<p>O aplicativo oferece navegação por categorias, busca, favoritos, histórico de reprodução e recursos de reprodução compatíveis com a experiência Roku.</p>

<h2>Suporte</h2>
<p>Para dúvidas relacionadas ao acesso ou funcionamento do aplicativo, utilize o contato de suporte informado na Loja de Canais Roku.</p>
