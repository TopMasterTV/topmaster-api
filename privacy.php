<h1>Política de Privacidade - TOP MASTER</h1>

<p>Esta Política de Privacidade descreve como o aplicativo TOP MASTER trata informações necessárias para o funcionamento do serviço.</p>

<h2>1. Finalidade do aplicativo</h2>
<p>O TOP MASTER é um aplicativo de reprodução e organização de mídia. O aplicativo não vende, fornece, comercializa ou adiciona canais, filmes, séries ou outros conteúdos à conta do usuário. Ele apenas apresenta e reproduz conteúdos previamente vinculados às credenciais utilizadas pelo usuário.</p>

<h2>2. Informações utilizadas</h2>
<p>Para permitir o acesso ao aplicativo, podem ser utilizadas informações de autenticação, como usuário e senha, além de dados técnicos necessários para comunicação com os serviços associados à conta.</p>

<h2>3. Uso das informações</h2>
<p>As informações são utilizadas exclusivamente para autenticação, carregamento dos conteúdos vinculados à conta, funcionamento dos recursos do aplicativo e suporte técnico.</p>

<h2>4. Compartilhamento</h2>
<p>O TOP MASTER não vende dados pessoais. Informações podem ser transmitidas aos serviços necessários ao funcionamento da conta e da reprodução de mídia, conforme a configuração associada ao usuário.</p>

<h2>5. Segurança</h2>
<p>São adotadas medidas técnicas razoáveis para proteger as informações utilizadas pelo aplicativo durante sua operação.</p>

<h2>6. Conteúdo de terceiros</h2>
<p>O TOP MASTER atua apenas como leitor/reprodutor de mídia. A disponibilidade, origem, licenciamento e classificação dos conteúdos acessados dependem dos serviços previamente vinculados à conta do usuário.</p>

<h2>7. Alterações</h2>
<p>Esta Política de Privacidade poderá ser atualizada quando necessário para refletir alterações no aplicativo ou em requisitos legais e de plataforma.</p>

<h2>8. Contato</h2>
<p>Em caso de dúvidas relacionadas à privacidade ou ao funcionamento do TOP MASTER, utilize o canal de suporte informado na página oficial do aplicativo.</p>

